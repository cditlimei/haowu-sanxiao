export function level37Layout(config,shuffle){
 const board=config.id===37?boards[config.variant-1]:null;
 if(!board)return null;
 const bySource=new Map(config.inventory.map(({type})=>[ITEMS[type].sourceItemId,type]));
 const scales=new Map([...bySource].map(([id,type])=>[type,sizes[id]]));
 const rad=Math.PI/180;
 const anchors=shuffle===0?board.map(([id,x,y,rotation,tiltX,tiltY])=>({
  type:bySource.get(id),x:x/405,y:y/600,rotation:rotation*rad,tiltX:tiltX*rad,tiltY:tiltY*rad,
 })):[];
 // The reference exposes mostly brown shells. Only the annotated cut faces
 // should point toward the camera in the initial pile.
 const unanchoredTiltY=shuffle===0?new Map([[bySource.get(46),(tilt)=>{
  const sign=tilt<0?-1:1;
  return sign*(Math.PI-Math.abs(tilt)*.88);
 }]]):null;
 const footprint=shuffle===0?referenceFootprints[config.variant-1]:null;
 return {anchors,scales,baseScale:1.69,coverage:true,unanchoredTiltY,footprint,
  footprintWeight:[.75,1.5,.75,1.5][config.variant-1]};
}
