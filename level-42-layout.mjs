export function level42Layout(config,shuffle){
 if(config.id!==42||!surfaces[config.variant-1])return null;
 const bySource=new Map(config.inventory.map(({type})=>[ITEMS[type].sourceItemId,type]));
 const scales=new Map([...bySource].map(([source,type])=>[type,scaleBySource[source]??1]));
 const rad=Math.PI/180;
 const anchors=shuffle===0?surfaces[config.variant-1].map(([id,x,y,rotation,tiltX,tiltY])=>({
  type:bySource.get(id),x:x/405,y:y/600,rotation:rotation*rad,tiltX:tiltX*rad,tiltY:tiltY*rad,
 })):[];
 return {anchors,scales,baseScale:1.78,coverage:true};
}
