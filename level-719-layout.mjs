export function level719Layout(config,shuffle){
 if(config.id!==719||!anchorsByVariant[config.variant])return null;
 const limeOpening=config.variant===1&&shuffle===0;
 const foregroundSizes=limeOpening?{
  1472:1.15,399:.91,293:.99,1441:.89,1126:1.10,1048:.85,
  86:1.09,1380:1.05,1148:.76,898:.88,1492:1.04,
 }:null;
 const scales=new Map(config.inventory.map(({type})=>{
  const id=ITEMS[type].sourceItemId;
  return [type,foregroundSizes?.[id]??relativeSizes[id]??1];
 }));
 const typeBySource=new Map(config.inventory.map(({type})=>[ITEMS[type].sourceItemId,type]));
 const rad=Math.PI/180;
 const anchors=shuffle===0?anchorsByVariant[config.variant].map(([sourceId,x,y,rotation,tiltX,tiltY])=>({
  type:typeBySource.get(sourceId),x:x/810,y:(limeOpening?y-(1040-y)*.050:y)/1200,
  rotation:rotation*rad,tiltX:tiltX*rad,tiltY:tiltY*rad,
 })):[];
 const unanchoredTiltY=new Map(config.inventory
  .filter(({type})=>[898,1492].includes(ITEMS[type].sourceItemId))
  .map(({type})=>[type,angle=>angle>(limeOpening?.70:ITEMS[type].sourceItemId===898?.2:0)?Math.PI-angle:angle]));
 return {
  scales,anchors,unanchoredTiltY,surfaceOrder:true,
  anchorScales:limeOpening?new Map([
   [1472,1.10],[399,1.03],[293,.99],[1441,.96],[1126,1.08],[1048,.91],
   [86,1.08],[1380,1.05],[1148,.93],[1492,1.06],
  ].map(([source,scale])=>[typeBySource.get(source),scale])):null,
  underlayScale:limeOpening?.79:1,tiltRange:limeOpening?1.65:undefined,
  upperGoalTypes:limeOpening?new Set(config.goals.map(({type})=>type)):null,clampAnchors:false,baseScale:[0,1.99,2.01,2.04,2.09][config.variant],
  coverage:true,footprint:footprints[config.variant],footprintWeight:3.1,
 };
}
